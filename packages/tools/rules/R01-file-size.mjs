// R1 file size: a file that is too big costs the AI a lot of context to read, and usually means mixed responsibilities.
// Criteria (any one → warning): over 400 lines; over 16KB (UTF-8 bytes). Line length is not counted: this repository writes many tokens per line
// (R10's own note), so a long-line limit only produced warnings nobody could clear; the byte limit already catches code crammed into long lines.
// Game code (games/*, the new-game templates; in a game installed from npm, the game folders), .js .mjs .html: warnings only, because a long file costs its reader
//       and breaks nothing. Over 1000 lines or 48KB gets the stronger text (split the file by system); 400-1000 lines or 16-48KB the plain one, except in the game's
//       art code (paths.mjs isArtFile: picture/, style/, art/, assets.js, art.js), which only meets the upper limit.
//       Engine and tools files: a warning only above that same upper limit. Between the limits they are a note and a list under --verbose: size is a cost, not a fault, and
//       a hundred warnings nobody will clear on a clean clone hid the few a person can act on.
// Scope: .js .mjs .d.ts .html under packages/engine/ (source, types, examples, tests, the root index.js index.d.ts and pages), packages/tools/, games/,
//       plus the hand-written .md under packages/engine/docs/ (directory list in paths.mjs).
import { walk, read, rel, GENERATED, reE, P } from './_lib.mjs';

const MAX_LINES = 400, MAX_BYTES = 16 * 1024;
const GAME_MAX_LINES = 1000, GAME_MAX_BYTES = 48 * 1024;   // game code: above these the warning says to split the file
const GAME_EXTS = ['.js', '.mjs', '.html'];
const GENERATED_DATA = /^\s*(\/\/|\/\*)\s*generated\b/im;   // a file whose first lines say `// generated by <tool>` is data, not counted
const isGame = f => P.under(f, P.GAMES_REL) || P.under(f, `${P.TOOLS_REL}/templates`) || P.MODE === 'game';
// Exempt from the line and byte limits: [path regex, reason]
const ALLOW_SIZE = [
  [reE('(index\\.d\\.ts|types\\/[^/]+\\.d\\.ts)$'), 'API declarations (d.ts): the AI reads the generated packages/engine/docs/api/<module>.md (one module per page), not the d.ts itself; ' +
    'grouped by domain (core / world / gameplay / physics) so types can reference each other and npm run types can check them all; splitting into small files only adds imports without saving context'],
  [reE('docs\\/AI\\.md$'), 'the AI index: one row per task; R22 caps its size at 11.5KB (an index grows with the engine, the recipes it points to stay small)'],
];
// Allowlist (path regex + reason)
const ALLOW = [
  [reE('tests\\/fixtures\\/'), 'test fixtures (generated or binary data)'],
  [reE('tests\\/specs(\\.mjs|\\/)'), 'test lists are stacked by feature; their size does not hurt engine readability'],
  ...GENERATED.map(r => [r, 'generated docs, not edited by hand']),
];

export default {
  id: 'R1', title: 'File size', game: true,
  run() {
    const out = [], listed = [];
    const files = P.MODE === 'game' ? [...new Set(P.gameDirs().flatMap(d => walk(rel(d) || '.', GAME_EXTS)))] : [P.INDEX_JS_REL, P.INDEX_DTS_REL, ...[P.TYPES_REL, ...P.SOURCE_DIRS_REL].flatMap(d => walk(d, ['.js', '.mjs', '.d.ts', '.html'])), ...walk(P.DOCS_REL, ['.md'])];
    for (const f of files) {
      if (ALLOW.some(([r]) => r.test(f))) continue;
      const text = read(f), L = text.split('\n');
      if (GENERATED_DATA.test(L.slice(0, 3).join('\n'))) continue;   // data a script writes (height map, baked table): its size says nothing about code
      const bytes = Buffer.byteLength(text);
      const why = [];
      // a game's art code (style/, art/, assets.js, art.js: vertex lists, palettes, generators) is long by nature and read one model at a time,
      // so it only meets the upper limit below; the 16KB warning is for gameplay files, where size means mixed systems
      const sizeOk = ALLOW_SIZE.some(([r]) => r.test(f)) || (isGame(f) && P.isArtFile(f));
      if (isGame(f) && GAME_EXTS.some(x => f.endsWith(x)) && (L.length > GAME_MAX_LINES || bytes > GAME_MAX_BYTES)) {
        const big = [L.length > GAME_MAX_LINES && `${L.length} lines (limit ${GAME_MAX_LINES})`, bytes > GAME_MAX_BYTES && `${(bytes / 1024).toFixed(1)}KB (limit ${GAME_MAX_BYTES / 1024}KB)`].filter(Boolean);
        out.push({ level: 'warn', file: f, line: 0, msg: `game file too large: ${big.join(', ')}`, fix: 'split this file by system (one system per file: combat.js, ui.js, saves.js…; content data in content/), and import them from main.js; a data file written by a script starts with `// generated by <tool>` and is not counted' });
        continue;
      }
      if (!sizeOk && L.length > MAX_LINES) why.push(`${L.length} lines (limit ${MAX_LINES})`);
      if (!sizeOk && bytes > MAX_BYTES) why.push(`${(bytes / 1024).toFixed(1)}KB (limit 16KB)`);
      if (why.length && !isGame(f) && L.length <= GAME_MAX_LINES && bytes <= GAME_MAX_BYTES) listed.push(`${f}: ${why.join(', ')}`);
      else if (why.length) out.push({ level: 'warn', file: f, line: 0, msg: `file too large: ${why.join(', ')}`, fix: 'split by responsibility (one thing per file)' });
    }
    if (listed.length) { out.note = `${listed.length} engine files are over ${MAX_LINES} lines or ${MAX_BYTES / 1024}KB, under the warning limit`; out.verbose = listed; }
    return out;
  },
};
